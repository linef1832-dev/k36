-- 📒 ตารางเก็บ "ประวัติการทำงานพนักงาน" (หน้าใหม่: ประวัติพนักงาน)
-- วิธีใช้: Supabase → SQL Editor → New query → วางทั้งไฟล์ → Run  (รันครั้งเดียวพอ)
-- ════════════════════════════════════════════════════════════════════
create table if not exists public.staff_records (
    id           bigint generated by default as identity primary key,
    user_id      text,                       -- id พนักงานในตาราง users
    user_name    text not null,              -- ชื่อพนักงาน (เก็บไว้ด้วย เผื่อเปลี่ยนชื่อ/ลบคนภายหลัง)
    record_date  date not null default current_date,   -- วันที่เกิดเรื่อง
    topic        text not null,              -- เรื่องที่ผิด เช่น "มาสาย"
    note         text,                       -- รายละเอียดเพิ่ม (ไม่บังคับ)
    created_by   text,                       -- ใครเป็นคนลง
    created_at   timestamptz not null default now()
);

create index if not exists staff_records_date_idx on public.staff_records (record_date desc);
create index if not exists staff_records_user_idx on public.staff_records (lower(user_name), record_date desc);

-- สิทธิ์แบบเดียวกับตารางอื่นของเว็บ (เว็บเช็คสิทธิ์เมนูเอง)
alter table public.staff_records enable row level security;
drop policy if exists "staff_records_all" on public.staff_records;
create policy "staff_records_all" on public.staff_records for all to anon, authenticated using (true) with check (true);
grant select, insert, update, delete on public.staff_records to anon, authenticated;

-- อัปเดตสดข้ามเครื่อง (ลงที่เครื่องหนึ่ง อีกเครื่องเห็นทันที)
do $$ begin
    alter publication supabase_realtime add table public.staff_records;
exception when duplicate_object then null; end $$;
